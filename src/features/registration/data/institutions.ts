export function searchInstitutions(query: string): string[] {
  if (!query || query.trim().length === 0) {
    // Return all Tamil Nadu colleges when focused or empty
    return TAMIL_NADU_COLLEGES_LIST;
  }
  const normalized = query.toLowerCase().trim();
  return TAMIL_NADU_COLLEGES_LIST.filter(inst => 
    inst.toLowerCase().includes(normalized)
  );
}
